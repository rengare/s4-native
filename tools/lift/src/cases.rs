//! Instruction forms of the game's code as conformance test cases: every
//! distinct non-branching instruction (registers and memory operand shape as
//! used, immediates by class) with its machine code and the generated Rust.

use crate::pe::Image;
use iced_x86::{Code, Decoder, DecoderOptions, Encoder, FlowControl, Instruction, Mnemonic, OpKind, Register, RflagsBits};
use std::collections::BTreeMap;
use std::fmt::Write;

fn eflags_mask(bits: u32) -> u32 {
    let mut m = 0;
    for (b, e) in [(RflagsBits::OF, 0x800), (RflagsBits::SF, 0x80), (RflagsBits::ZF, 0x40), (RflagsBits::AF, 0x10), (RflagsBits::CF, 1), (RflagsBits::PF, 4), (RflagsBits::DF, 0x400)] {
        if bits & b != 0 {
            m |= e;
        }
    }
    m
}

fn is_shift_like(m: Mnemonic) -> bool {
    use Mnemonic as M;
    matches!(m, M::Shl | M::Shr | M::Sar | M::Sal | M::Rol | M::Ror | M::Rcl | M::Rcr | M::Shld | M::Shrd | M::Bt | M::Bts | M::Btr | M::Btc | M::Psllw | M::Pslld | M::Psllq | M::Psrlw | M::Psrld | M::Psrlq | M::Psraw | M::Psrad)
}

/// Immediate class: operands that behave alike share a case.
fn imm_class(v: u64) -> u32 {
    match v as u32 as i32 {
        0 => 0,
        1 => 1,
        -1 => 2,
        2..=0x1f => 3,
        0x20..=0xff => 4,
        0x100..=0xffff => 5,
        i32::MIN..=-2 => 6,
        _ => 7,
    }
}

pub fn generate(paths: &[String], out_rs: &str) {
    let mut forms: BTreeMap<String, (Instruction, usize)> = BTreeMap::new();
    for path in paths {
        let img = Image::load(path);
        for s in &img.sections {
            if s.flags & 0x2000_0000 == 0 {
                continue;
            }
            let mut d = Decoder::with_ip(32, &s.data, (img.base + s.rva) as u64, DecoderOptions::NONE);
            while d.can_decode() {
                let ins = d.decode();
                if ins.is_invalid() || ins.flow_control() != FlowControl::Next || ins.mnemonic() == Mnemonic::Nop {
                    continue;
                }
                // Port I/O is privileged; cpuid and rdtsc answer per machine (the lifted code has a fixed profile).
                if matches!(ins.mnemonic(), Mnemonic::In | Mnemonic::Out | Mnemonic::Insb | Mnemonic::Insw | Mnemonic::Insd | Mnemonic::Outsb | Mnemonic::Outsw | Mnemonic::Outsd | Mnemonic::Cpuid | Mnemonic::Rdtsc) {
                    continue;
                }
                if ins.segment_prefix() != Register::None {
                    continue;
                }
                let mut key = format!("{:?}", ins.code());
                for i in 0..ins.op_count() {
                    match ins.op_kind(i) {
                        OpKind::Register => write!(key, " r{:?}", ins.op_register(i)).unwrap(),
                        OpKind::Memory => write!(key, " m{:?}+{:?}*{}", ins.memory_base(), ins.memory_index(), ins.memory_index_scale()).unwrap(),
                        OpKind::Immediate8 | OpKind::Immediate8to16 | OpKind::Immediate8to32 | OpKind::Immediate16 | OpKind::Immediate32 => {
                            let v = ins.immediate(i);
                            if is_shift_like(ins.mnemonic()) {
                                write!(key, " i{v}").unwrap()
                            } else {
                                write!(key, " i{}", imm_class(v)).unwrap()
                            }
                        }
                        k => write!(key, " k{k:?}").unwrap(),
                    }
                }
                if ins.has_rep_prefix() || ins.has_repne_prefix() {
                    key.push_str(" rep");
                }
                forms.entry(key).or_insert((ins, 0)).1 += 1;
            }
        }
    }
    let mut src = String::new();
    src.push_str("// Generated by `lift cases`; do not edit.\n");
    src.push_str(crate::header().replace("use super::*;\n", "").as_str());
    src.push_str("pub static DISP: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(0);\n");
    let mut table = String::new();
    let mut unsupported: BTreeMap<String, usize> = BTreeMap::new();
    let mut n = 0;
    for (key, (ins, count)) in &forms {
        let name = format!("case_{n:05}");
        let body = match crate::lift_single(&name, ins) {
            Ok(b) => b,
            Err(e) => {
                *unsupported.entry(format!("{:?}: {}", ins.mnemonic(), e.0)).or_default() += count;
                continue;
            }
        };
        // Encode with a placeholder 32-bit displacement.
        let mut enc_ins = *ins;
        let has_mem = (0..ins.op_count()).any(|i| ins.op_kind(i) == OpKind::Memory);
        if has_mem {
            enc_ins.set_memory_displ_size(4);
            enc_ins.set_memory_displacement64(0);
        }
        let mut e = Encoder::new(32);
        if let Err(er) = e.encode(&enc_ins, 0x1000) {
            *unsupported.entry(format!("{:?}: cannot re-encode ({er})", ins.mnemonic())).or_default() += count;
            continue;
        }
        let offs = e.get_constant_offsets();
        let bytes = e.take_buffer();
        let (base, index, scale) = if has_mem {
            let reg = |r: Register| if r == Register::None { 255u8 } else { r.full_register32().number() as u8 };
            (reg(ins.memory_base()), reg(ins.memory_index()), ins.memory_index_scale() as u8)
        } else {
            (255, 255, 1)
        };
        let disp_off = if has_mem { offs.displacement_offset() as i32 } else { -1 };
        let rep = ins.has_rep_prefix() || ins.has_repne_prefix();
        let mn = ins.mnemonic();
        let div = matches!(mn, Mnemonic::Div | Mnemonic::Idiv | Mnemonic::Fidiv | Mnemonic::Fidivr);
        let text = crate::text(ins).replace('"', "'");
        let string = crate::emit::is_string_op(ins);
        let memfloat = if has_mem {
            use iced_x86::MemorySize as S;
            match ins.memory_size() {
                S::Float32 => 1,
                S::Float64 => 2,
                S::Float80 => 3,
                _ => 0,
            }
        } else {
            0
        };
        src.push_str(&body);
        writeln!(
            table,
            "    Case {{ name: \"{key}\", text: \"{text}\", bytes: &{bytes:?}, disp_offset: {disp_off}, base: {base}, index: {index}, scale: {scale}, undefined: {undef:#x}, rep: {rep}, div: {div}, string: {string}, memfloat: {memfloat}, sources: {count}, run: {name} }},",
            undef = eflags_mask(ins.rflags_undefined()) | extra_undefined(ins),
        )
        .unwrap();
        n += 1;
    }
    writeln!(src, "pub struct Case {{ pub name: &'static str, pub text: &'static str, pub bytes: &'static [u8], pub disp_offset: i32, pub base: u8, pub index: u8, pub scale: u8, pub undefined: u32, pub rep: bool, pub div: bool, pub string: bool, pub memfloat: u8, pub sources: usize, pub run: fn(&mut Cpu) }}\n").unwrap();
    writeln!(src, "pub static CASES: &[Case] = &[\n{table}];").unwrap();
    std::fs::write(out_rs, src).unwrap();
    let mut gaps = String::new();
    let mut v: Vec<_> = unsupported.into_iter().collect();
    v.sort_by_key(|x| std::cmp::Reverse(x.1));
    for (k, c) in v {
        writeln!(gaps, "{c}\t{k}").unwrap();
    }
    std::fs::write(format!("{out_rs}.unsupported.txt"), gaps).unwrap();
    eprintln!("{} cases ({} forms unsupported)", n, forms.len() - n);
    let _ = Code::INVALID;
}

/// Flags the manuals leave undefined for shifts and rotates by other than
/// one bit (the count is a register or an immediate that is not 1), which
/// iced does not list.
fn extra_undefined(ins: &Instruction) -> u32 {
    use Mnemonic as M;
    if !matches!(ins.mnemonic(), M::Shl | M::Shr | M::Sar | M::Sal | M::Rol | M::Ror | M::Rcl | M::Rcr | M::Shld | M::Shrd) {
        return 0;
    }
    let last = ins.op_count() - 1;
    let one = ins.op_count() == 1 || (matches!(ins.op_kind(last), OpKind::Immediate8) && ins.immediate(last) == 1);
    if one { 0 } else { 0x800 }
}
