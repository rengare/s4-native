#!/usr/bin/env python3
"""Generate naked jmp forwarders for every export of an original DLL.

Usage: gen_forwarders.py <original.dll> <out.rs> <crate-src.rs ...>

Each forwarder jumps through ORIG[i], which the proxy fills from the renamed
original DLL at load. Exports the crate sources implement themselves
(`implement!("<name>", ...)`) get no forwarder. Every export gets an `IDX_*` slot constant, so the crate can
call any original function.
"""
import re
import sys
from collections import Counter

import pefile


def main() -> None:
    dll, out = sys.argv[1], sys.argv[2]
    overridden = set()
    for src in sys.argv[3:]:
        overridden |= set(re.findall(r'implement!\(\s*"([^"]+)"', open(src).read()))
    pe = pefile.PE(dll, fast_load=True)
    pe.parse_data_directories([pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
    names = sorted(e.name.decode() for e in pe.DIRECTORY_ENTRY_EXPORT.symbols if e.name)
    missing = overridden - set(names)
    if missing:
        sys.exit(f"unknown overrides: {missing}")

    lines = [
        "// @generated by tools/gen_forwarders.py — do not edit.",
        "",
        f"pub const COUNT: usize = {len(names)};",
        "",
        "/// Export names of the original DLL, index = slot in `ORIG`.",
        "pub static NAMES: [&str; COUNT] = [",
        *(f'    "{n}",' for n in names),
        "];",
        "",
    ]
    bases = [base(n) for n in names]
    seen: Counter[str] = Counter()
    for i, n in enumerate(names):
        b = bases[i]
        seen[b] += 1
        # Overloads (same method name) are numbered in mangled-name order.
        ident = b if bases.count(b) == 1 else f"{b}_{seen[b] - 1}"
        lines.append(f'#[allow(dead_code)]\npub const IDX_{ident}: usize = {i};  // {n}')
        if n not in overridden:
            lines.append(f'forward!({i}, "{n}");')
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


def base(mangled: str) -> str:
    """?InitEngine@IGfxEngine@@... -> INITENGINE"""
    return mangled.lstrip("?").split("@")[0].upper()


if __name__ == "__main__":
    main()
